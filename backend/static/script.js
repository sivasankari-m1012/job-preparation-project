let jobs = [];

async function loadJobs() {
    try {
        const response = await fetch("/api/jobs");

        if (!response.ok) {
            throw new Error("Failed to load jobs");
        }

        jobs = await response.json();
        displayJobs();
    } catch (error) {
        console.error("Error loading jobs:", error);
    }
}

function displayJobs() {
    const jobsContainer = document.getElementById("jobs");

    jobsContainer.innerHTML = "";

    jobs.forEach(function(job) {
        const jobCard = document.createElement("div");

        jobCard.className = "job-card";

        jobCard.innerHTML = `
            <h3>${job.company}</h3>

            <p>
                <strong>Role:</strong>
                ${job.role}
            </p>

            <p>
                <strong>Status:</strong>
            </p>

            <select onchange="changeStatus(${job.id}, this.value)">
                <option value="Applied" ${job.status === "Applied" ? "selected" : ""}>
                    Applied
                </option>

                <option value="Online Assessment" ${job.status === "Online Assessment" ? "selected" : ""}>
                    Online Assessment
                </option>

                <option value="Technical Interview" ${job.status === "Technical Interview" ? "selected" : ""}>
                    Technical Interview
                </option>

                <option value="HR Interview" ${job.status === "HR Interview" ? "selected" : ""}>
                    HR Interview
                </option>

                <option value="Selected" ${job.status === "Selected" ? "selected" : ""}>
                    Selected
                </option>

                <option value="Rejected" ${job.status === "Rejected" ? "selected" : ""}>
                    Rejected
                </option>
            </select>

            <div class="job-buttons">
                <button onclick="openPreparationKit(${job.id})">
                    Preparation Kit
                </button>

                <button onclick="deleteJob(${job.id})">
                    Delete
                </button>
            </div>
        `;

        jobsContainer.appendChild(jobCard);
    });
}

document
    .getElementById("jobForm")
    .addEventListener("submit", async function(event) {

        event.preventDefault();

        const company =
            document.getElementById("company").value.trim();

        const role =
            document.getElementById("role").value.trim();

        const status =
            document.getElementById("status").value;

        const job = {
            company: company,
            role: role,
            status: status
        };

        try {
            const response = await fetch("/api/jobs", {
                method: "POST",
                headers: {
                    "Content-Type": "application/json"
                },
                body: JSON.stringify(job)
            });

            if (!response.ok) {
                throw new Error("Failed to add job");
            }

            document
                .getElementById("jobForm")
                .reset();

            loadJobs();

        } catch (error) {
            console.error("Error adding job:", error);
        }
    });

async function changeStatus(jobId, newStatus) {
    try {
        const response = await fetch(`/api/jobs/${jobId}`, {
            method: "PUT",
            headers: {
                "Content-Type": "application/json"
            },
            body: JSON.stringify({
                status: newStatus
            })
        });

        if (!response.ok) {
            throw new Error("Failed to update status");
        }

        loadJobs();

    } catch (error) {
        console.error("Error changing status:", error);
    }
}

async function deleteJob(jobId) {
    try {
        const response = await fetch(`/api/jobs/${jobId}`, {
            method: "DELETE"
        });

        if (!response.ok) {
            throw new Error("Failed to delete job");
        }

        loadJobs();

    } catch (error) {
        console.error("Error deleting job:", error);
    }
}

function openPreparationKit(jobId) {
    const job = jobs.find(function(job) {
        return job.id === jobId;
    });

    if (!job) {
        console.error("Job not found");
        return;
    }

    const companyName = job.company.trim();

    const companyKey = Object.keys(preparationData).find(
        function(company) {
            return company.toLowerCase() ===
                   companyName.toLowerCase();
        }
    );

    const prep = preparationData[companyKey];

    if (!prep) {
        alert(
            "Preparation kit is not available for " +
            companyName +
            " yet."
        );
        return;
    }

    const preparationKit =
        document.getElementById("preparationKit");

    preparationKit.style.display = "block";

    document.getElementById(
        "prepCompanyName"
    ).textContent =
        companyName + " Preparation Kit";

    displayList(
        "technicalTopics",
        prep.technical
    );

    displayList(
        "codingTopics",
        prep.coding
    );

    displayList(
        "aptitudeTopics",
        prep.aptitude
    );

    displayList(
        "interviewQuestions",
        prep.interview
    );

    displayList(
        "resumePreparation",
        prep.resume
    );

    displayResources(
        prep.resources
    );

    preparationKit.scrollIntoView({
        behavior: "smooth"
    });
}

function displayList(elementId, items) {
    const element =
        document.getElementById(elementId);

    element.innerHTML = "";

    items.forEach(function(item) {
        const li =
            document.createElement("li");

        li.textContent = item;

        element.appendChild(li);
    });
}

function displayResources(resources) {
    const container =
        document.getElementById("resources");

    container.innerHTML = "";

    resources.forEach(function(resource) {
        const link =
            document.createElement("a");

        link.href =
            resource.url;

        link.textContent =
            resource.name;

        link.target =
            "_blank";

        link.rel =
            "noopener noreferrer";

        link.className =
            "resource-link";

        container.appendChild(link);
    });
}

