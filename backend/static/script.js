const STATUSES = [
    "Applied",
    "Online Assessment",
    "Technical Interview",
    "HR Interview",
    "Selected",
    "Rejected"
];

let jobs = [];
let searchTimer = null;

/* ---------- small helpers ---------- */

function showMessage(text) {
    const box = document.getElementById("message");
    box.textContent = text;
    box.hidden = !text;
}

// Turns the API's {"error": ..., "details": {...}} into one readable line.
async function apiError(response, fallback) {
    try {
        const body = await response.json();
        const details = body.details
            ? Object.entries(body.details).map(function(entry) {
                  return entry[0] + " " + entry[1];
              }).join("; ")
            : "";
        return details || body.error || fallback;
    } catch (error) {
        return fallback;
    }
}

function el(tag, text, className) {
    const node = document.createElement(tag);
    if (text !== undefined && text !== null) {
        node.textContent = text;     // textContent => user data can never inject HTML
    }
    if (className) {
        node.className = className;
    }
    return node;
}

function formatDate(isoString) {
    // Date-only values (deadline) are shown as written, with no timezone shift.
    const value = isoString.length === 10 ? isoString + "T00:00:00" : isoString;
    return new Date(value).toLocaleDateString(undefined, {
        day: "numeric", month: "short", year: "numeric"
    });
}

/* ---------- loading ---------- */

async function loadJobs() {
    const params = new URLSearchParams();
    const search = document.getElementById("search").value.trim();
    const status = document.getElementById("filterStatus").value;
    const sort = document.getElementById("sortBy").value.split(":");

    if (search) { params.set("q", search); }
    if (status) { params.set("status", status); }
    params.set("sort", sort[0]);
    params.set("order", sort[1]);

    try {
        const response = await fetch("/api/jobs?" + params.toString());

        if (!response.ok) {
            throw new Error(await apiError(response, "Failed to load jobs"));
        }

        jobs = await response.json();
        showMessage("");
        displayJobs();
    } catch (error) {
        showMessage(error.message);
    }

    loadStats();
}

async function loadStats() {
    try {
        const response = await fetch("/api/stats");
        if (!response.ok) { return; }

        const stats = await response.json();
        const container = document.getElementById("stats");
        container.innerHTML = "";

        const total = el("div", null, "stat");
        total.appendChild(el("strong", stats.total));
        total.appendChild(el("span", "Total"));
        container.appendChild(total);

        STATUSES.forEach(function(name) {
            const box = el("div", null, "stat");
            box.appendChild(el("strong", stats.by_status[name] || 0));
            box.appendChild(el("span", name));
            container.appendChild(box);
        });
    } catch (error) {
        console.error("Error loading stats:", error);
    }
}

/* ---------- rendering ---------- */

function displayJobs() {
    const jobsContainer = document.getElementById("jobs");
    jobsContainer.innerHTML = "";

    if (jobs.length === 0) {
        jobsContainer.appendChild(el("p", "No applications found.", "empty"));
        return;
    }

    jobs.forEach(function(job) {
        const card = el("div", null, "job-card");

        card.appendChild(el("h3", job.company));

        const role = el("p");
        role.appendChild(el("strong", "Role: "));
        role.appendChild(document.createTextNode(job.role));
        card.appendChild(role);

        if (job.location) {
            card.appendChild(el("p", "📍 " + job.location, "meta"));
        }
        if (job.deadline) {
            card.appendChild(el("p", "⏰ Deadline: " + formatDate(job.deadline), "meta"));
        }
        if (job.url) {
            const link = el("a", "Job link", "meta-link");
            link.href = job.url;
            link.target = "_blank";
            link.rel = "noopener noreferrer";
            card.appendChild(link);
        }
        if (job.notes) {
            card.appendChild(el("p", job.notes, "notes"));
        }

        card.appendChild(el("p", null)).appendChild(el("strong", "Status:"));

        const select = el("select");
        STATUSES.forEach(function(name) {
            const option = el("option", name);
            option.value = name;
            option.selected = name === job.status;
            select.appendChild(option);
        });
        select.addEventListener("change", function() {
            changeStatus(job.id, select.value);
        });
        card.appendChild(select);

        const history = el("div", null, "history");
        history.hidden = true;

        const buttons = el("div", null, "job-buttons");

        const prepButton = el("button", "Preparation Kit");
        prepButton.addEventListener("click", function() {
            openPreparationKit(job.id);
        });

        const historyButton = el("button", "History", "secondary");
        historyButton.addEventListener("click", function() {
            toggleHistory(job.id, history);
        });

        const deleteButton = el("button", "Delete", "danger");
        deleteButton.addEventListener("click", function() {
            deleteJob(job.id, job.company);
        });

        buttons.appendChild(prepButton);
        buttons.appendChild(historyButton);
        buttons.appendChild(deleteButton);
        card.appendChild(buttons);
        card.appendChild(history);

        jobsContainer.appendChild(card);
    });
}

async function toggleHistory(jobId, container) {
    if (!container.hidden) {
        container.hidden = true;
        return;
    }

    try {
        const response = await fetch("/api/jobs/" + jobId);
        if (!response.ok) {
            throw new Error(await apiError(response, "Failed to load history"));
        }

        const job = await response.json();
        container.innerHTML = "";
        container.appendChild(el("h4", "Status history"));

        job.history.forEach(function(entry) {
            const text = entry.from_status
                ? entry.from_status + " → " + entry.to_status
                : "Added as " + entry.to_status;
            container.appendChild(el("p", text + "  ·  " + formatDate(entry.changed_at)));
        });

        container.hidden = false;
    } catch (error) {
        showMessage(error.message);
    }
}

/* ---------- actions ---------- */

document
    .getElementById("jobForm")
    .addEventListener("submit", async function(event) {

        event.preventDefault();

        const job = {
            company: document.getElementById("company").value.trim(),
            role: document.getElementById("role").value.trim(),
            status: document.getElementById("status").value,
            location: document.getElementById("location").value.trim(),
            url: document.getElementById("url").value.trim(),
            notes: document.getElementById("notes").value.trim(),
            deadline: document.getElementById("deadline").value
        };

        try {
            const response = await fetch("/api/jobs", {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify(job)
            });

            if (!response.ok) {
                throw new Error(await apiError(response, "Failed to add job"));
            }

            document.getElementById("jobForm").reset();
            loadJobs();

        } catch (error) {
            showMessage(error.message);
        }
    });

async function changeStatus(jobId, newStatus) {
    try {
        const response = await fetch("/api/jobs/" + jobId, {
            method: "PATCH",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ status: newStatus })
        });

        if (!response.ok) {
            throw new Error(await apiError(response, "Failed to update status"));
        }

        loadJobs();

    } catch (error) {
        showMessage(error.message);
        loadJobs();
    }
}

async function deleteJob(jobId, company) {
    if (!confirm("Delete the application for " + company + "?")) {
        return;
    }

    try {
        const response = await fetch("/api/jobs/" + jobId, {
            method: "DELETE"
        });

        if (!response.ok) {
            throw new Error(await apiError(response, "Failed to delete job"));
        }

        loadJobs();

    } catch (error) {
        showMessage(error.message);
    }
}

/* ---------- filters ---------- */

(function setupFilters() {
    const filter = document.getElementById("filterStatus");

    STATUSES.forEach(function(name) {
        const option = el("option", name);
        option.value = name;
        filter.appendChild(option);
    });

    filter.addEventListener("change", loadJobs);
    document.getElementById("sortBy").addEventListener("change", loadJobs);

    document.getElementById("search").addEventListener("input", function() {
        clearTimeout(searchTimer);
        searchTimer = setTimeout(loadJobs, 250);   // wait until typing pauses
    });
})();

function openPreparationKit(jobId) {
    const job = jobs.find(function(job) {
        return job.id === jobId;
    });

    if (!job) {
        console.error("Job not found");
        return;
    }

    const companyName = job.company.trim();

    const companyKey = Object.keys(preparationData).find(
        function(company) {
            return company.toLowerCase() ===
                   companyName.toLowerCase();
        }
    );

    const prep = preparationData[companyKey];

    if (!prep) {
        alert(
            "Preparation kit is not available for " +
            companyName +
            " yet."
        );
        return;
    }

    const preparationKit =
        document.getElementById("preparationKit");

    preparationKit.style.display = "block";

    document.getElementById(
        "prepCompanyName"
    ).textContent =
        companyName + " Preparation Kit";

    displayList(
        "technicalTopics",
        prep.technical
    );

    displayList(
        "codingTopics",
        prep.coding
    );

    displayList(
        "aptitudeTopics",
        prep.aptitude
    );

    displayList(
        "interviewQuestions",
        prep.interview
    );

    displayList(
        "resumePreparation",
        prep.resume
    );

    displayResources(
        prep.resources
    );

    preparationKit.scrollIntoView({
        behavior: "smooth"
    });
}

function displayList(elementId, items) {
    const element =
        document.getElementById(elementId);

    element.innerHTML = "";

    items.forEach(function(item) {
        const li =
            document.createElement("li");

        li.textContent = item;

        element.appendChild(li);
    });
}

function displayResources(resources) {
    const container =
        document.getElementById("resources");

    container.innerHTML = "";

    resources.forEach(function(resource) {
        const link =
            document.createElement("a");

        link.href =
            resource.url;

        link.textContent =
            resource.name;

        link.target =
            "_blank";

        link.rel =
            "noopener noreferrer";

        link.className =
            "resource-link";

        container.appendChild(link);
    });
}

